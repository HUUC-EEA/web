import { readdir, readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { join, extname, sep as SEP } from "node:path";
import subsetFont from "subset-font";

const ROOT = process.cwd();
const SCAN_DIRS = ["app"];
const PUBLIC_FONTS = join(ROOT, "public", "fonts");

const PIXEL_SOURCES = [
  {
    file: "node_modules/@fontsource/fusion-pixel-12px-proportional-sc/files/fusion-pixel-12px-proportional-sc-latin-400-normal.woff2",
    out: "fusion-pixel-12px-proportional-sc.woff2",
  },
  {
    file: "node_modules/@fontsource/fusion-pixel-12px-monospaced-sc/files/fusion-pixel-12px-monospaced-sc-latin-400-normal.woff2",
    out: "fusion-pixel-12px-monospaced-sc.woff2",
  },
];

// 得意黑在 npm 上是 cn-font-split 切好的 63 个分片，直接引入会拉下约 1MB；
// 这里按站点用字重新裁剪，并把生成的 @font-face 写成 app/fonts/smiley-sans.css
const SMILEY = {
  css: "node_modules/@chinese-fonts/dyh/dist/SmileySans-Oblique/result.css",
  sliceDir: "node_modules/@chinese-fonts/dyh/dist/SmileySans-Oblique",
  outDir: join(PUBLIC_FONTS, "smiley"),
  outFile: join(ROOT, "app", "fonts", "smiley-sans.css"),
  family: "Smiley Sans Oblique",
};

async function collectSourceFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await collectSourceFiles(full)));
    else if ([".tsx", ".ts", ".css"].includes(extname(entry.name))) out.push(full);
  }
  return out;
}

const files = [];
for (const dir of SCAN_DIRS) {
  // 排除自动生成的字体 CSS，避免把注释里的字也算进字符集
  files.push(...(await collectSourceFiles(join(ROOT, dir))).filter((f) => !f.includes(`app${SEP}fonts${SEP}`)));
}

const chars = new Set();
for (const file of files) {
  const text = await readFile(file, "utf8");
  for (const ch of text) {
    const cp = ch.codePointAt(0);
    // 汉字、扩展 A、兼容表意文字
    if ((cp >= 0x4e00 && cp <= 0x9fff) || (cp >= 0x3400 && cp <= 0x4dbf) || (cp >= 0xf900 && cp <= 0xfaff)) {
      chars.add(ch);
    }
  }
}

// ASCII 可打印字符 + 中文标点，保证英文/数字/符号也走同一套字形
for (let cp = 0x20; cp <= 0x7e; cp++) chars.add(String.fromCodePoint(cp));
for (const ch of "、。！？：；，·—…“”‘’（）《》【】％＋｜～↗") chars.add(ch);

const charset = [...chars].join("");
await mkdir(PUBLIC_FONTS, { recursive: true });

for (const src of PIXEL_SOURCES) {
  const buf = await readFile(join(ROOT, src.file));
  const subset = await subsetFont(buf, charset, { targetFormat: "woff2" });
  await writeFile(join(PUBLIC_FONTS, src.out), subset);
  console.log(
    `${src.out}: ${(buf.length / 1024).toFixed(0)}KB -> ${(subset.length / 1024).toFixed(1)}KB (${chars.size} chars)`
  );
}

/* ---------- 得意黑：按分片裁剪 ---------- */

function parseRanges(text) {
  return text.split(",").map((part) => {
    const m = part.trim().match(/^U\+([0-9A-Fa-f]+)(?:-([0-9A-Fa-f]+))?$/);
    if (!m) return null;
    const start = parseInt(m[1], 16);
    return [start, m[2] ? parseInt(m[2], 16) : start];
  }).filter(Boolean);
}

const cssText = await readFile(join(ROOT, SMILEY.css), "utf8");
const faces = [...cssText.matchAll(/@font-face\{([^}]*)\}/g)].map((m) => {
  const body = m[1];
  const file = body.match(/url\("\.\/([^"]+\.woff2)"\)/)[1];
  const range = body.match(/unicode-range:([^;]+);/)[1];
  return { file, ranges: parseRanges(range) };
});

// 每个字符归到覆盖它的第一个分片，避免同一字符被重复打包
const sliceChars = new Map(faces.map((f) => [f.file, []]));
const uncovered = [];
for (const ch of chars) {
  const cp = ch.codePointAt(0);
  const hit = faces.find((f) => f.ranges.some(([lo, hi]) => cp >= lo && cp <= hi));
  if (hit) sliceChars.get(hit.file).push(ch);
  else uncovered.push(ch);
}

await rm(SMILEY.outDir, { recursive: true, force: true });
await mkdir(SMILEY.outDir, { recursive: true });

let totalIn = 0;
let totalOut = 0;
let kept = 0;
const rules = [];

for (const face of faces) {
  const slice = sliceChars.get(face.file);
  if (!slice.length) continue;
  const buf = await readFile(join(ROOT, SMILEY.sliceDir, face.file));
  const subset = await subsetFont(buf, slice.join(""), { targetFormat: "woff2" });
  totalIn += buf.length;
  totalOut += subset.length;
  kept++;
  await writeFile(join(SMILEY.outDir, face.file), subset);
  const range = slice
    .map((ch) => "U+" + ch.codePointAt(0).toString(16).toUpperCase())
    .join(",");
  rules.push(
    `@font-face{font-family:"${SMILEY.family}";src:url("/fonts/smiley/${face.file}") format("woff2");font-style:normal;font-weight:400;font-display:swap;unicode-range:${range};}`
  );
}

const header = `/* Generated by \`npm run fonts:subset\` - do not edit.
   Smiley Sans Oblique (SIL OFL 1.1, atelierAnchor), subset per used glyph. */\n`;
await mkdir(join(ROOT, "app", "fonts"), { recursive: true });
await writeFile(SMILEY.outFile, header + rules.join("\n") + "\n");

console.log(
  `smiley-sans: ${kept}/${faces.length} 分片, ${(totalIn / 1024).toFixed(0)}KB -> ${(totalOut / 1024).toFixed(1)}KB`
);
if (uncovered.length) {
  console.log(`未覆盖字符（会回退到 Noto Sans SC）: ${uncovered.join("")}`);
}
